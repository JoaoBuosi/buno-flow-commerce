-- Buno Flow Commerce / Buno Core MVP: esquema inicial PostgreSQL 15+
-- Executar somente em base vazia; para bases existentes criar migracao de dados.
-- A aplicação usa conexão PostgreSQL exclusivamente no backend. NUNCA enviar essa conexão ao navegador.
BEGIN;

CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id VARCHAR(80) NOT NULL,
    customer_id VARCHAR(120) NOT NULL,
    total NUMERIC(19,2) NOT NULL CHECK (total > 0),
    status VARCHAR(30) NOT NULL DEFAULT 'CREATED'
        CHECK (status IN ('CREATED', 'REVIEWED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_orders_tenant ON public.orders(tenant_id);

CREATE TABLE IF NOT EXISTS public.workflow_requests (
    id UUID PRIMARY KEY,
    tenant_id VARCHAR(80) NOT NULL,
    order_id BIGINT NOT NULL REFERENCES public.orders(id),
    idempotency_key VARCHAR(120) NOT NULL,
    desired_status VARCHAR(30) NOT NULL CHECK (desired_status = 'REVIEWED'),
    reason VARCHAR(1000) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING_APPROVAL'
        CHECK (status IN ('PENDING_APPROVAL','APPROVED','REJECTED','EXECUTED')),
    requested_by VARCHAR(30) NOT NULL,
    approved_by VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    version BIGINT,
    CONSTRAINT uq_workflow_tenant_idempotency UNIQUE (tenant_id, idempotency_key)
);
CREATE INDEX IF NOT EXISTS idx_workflow_tenant_status
    ON public.workflow_requests(tenant_id, status);

CREATE TABLE IF NOT EXISTS public.workflow_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id VARCHAR(80) NOT NULL,
    workflow_id UUID NOT NULL REFERENCES public.workflow_requests(id),
    actor_role VARCHAR(30) NOT NULL,
    event_type VARCHAR(30) NOT NULL,
    details VARCHAR(300) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_workflow_audit_scope
    ON public.workflow_audit_events(tenant_id, workflow_id);

-- Defesa em profundidade: tabelas no schema public nao devem ser acessadas via chave anon.
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.workflow_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.workflow_audit_events ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.orders, public.workflow_requests,
    public.workflow_audit_events FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.orders_id_seq,
    public.workflow_audit_events_id_seq FROM anon, authenticated;

COMMIT;
